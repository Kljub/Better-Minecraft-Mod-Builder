package sheepfromheaven.screenspec.runtime.block;

import java.util.Map;

/**
 * Mirrors the {@code BlockSpec} shape exported by the MC Screen Designer web tool (see {@code
 * webapp/lib/types.ts}). Field names and JSON shape must stay in sync with that file.
 */
public final class BlockSpec {
    public String id;
    public String modId;
    public String displayName;
    /** Single texture applied to all 6 faces (cube_all) — informational only here, see {@link
     * sheepfromheaven.screenspec.runtime.item.ItemSpec#texture}'s javadoc for why. */
    public String texture;
    /** Per-face texture overrides ("up"/"down"/"north"/"south"/"east"/"west"), unset faces fall
     * back to {@link #texture} — informational only here (same reason as {@link #texture}); the
     * real model JSON is generated by the webapp exporter at export time, not by this runtime. */
    public Map<String, String> faceTextures;
    /** {@code "cube"} (default), {@code "chest"}: a working chest drawn with the skin the
     * webapp exports to {@code textures/entity/chest/<id>.png}, see {@link SpecChestBlock}, or
     * {@code "custom"}: drawn by an entity model, see {@link SpecModelBlock} and {@link #parts}. */
    public String model = "cube";
    /** {@code "custom"}: id of the webapp entity model it was made from — informational only. */
    public String customModel;
    /** {@code "custom"}: whether a model bigger than one block was cut into parts — informational,
     * {@link #parts} already holds the result. */
    public boolean multiblock;
    /** {@code "custom"}: the occupied 16³ cells, filled by the webapp exporter. Offset 0,0,0 is the
     * placed block; every other cell is a part block {@code <id>_p_<x>_<y>_<z>} (negative = "m1"). */
    public java.util.List<Part> parts;

    public static final class Part {
        /** in blocks, for facing north */
        public int[] offset = {0, 0, 0};
        /** outline/collision boxes in pixels (0..16): x1, y1, z1, x2, y2, z2 */
        public java.util.List<double[]> boxes;
    }
    public double hardness = 1.5;
    public double resistance = 6;
    public boolean requiresTool;
    /** Light level emitted, 0-15. */
    public int luminance;
    /** {@code "stone" | "wood" | "metal" | "gravel" | "grass" | "glass" | "wool" | "sand"} */
    public String soundType = "stone";
    /** Whether to also register a BlockItem so the block can be held/placed. */
    public boolean hasItem = true;
    public String creativeTab = "custom";
    /** Further tabs besides {@link #creativeTab}; {@code creativeTab = "none"} puts it in no tab (only /give). */
    public java.util.List<String> extraCreativeTabs;
}
